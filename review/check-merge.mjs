import {mkdir, readFile, writeFile, copyFile} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {setTimeout as pause} from 'node:timers/promises';
const folder=path.dirname(fileURLToPath(import.meta.url));
const fixtures=path.join(folder,'merge-fixtures');
const downloads=path.join(folder,'merge-downloads',String(Date.now()));
await mkdir(downloads,{recursive:true});
const targets=await(await fetch('http://127.0.0.1:9286/json')).json();
const ws=new WebSocket(targets.find(target=>target.type==='page').webSocketDebuggerUrl);
await new Promise(resolve=>ws.addEventListener('open',resolve,{once:true}));
let id=0;const waiting=new Map();const errors=[];const requests=[];
ws.addEventListener('message',({data})=>{const msg=JSON.parse(data);if(msg.id){const item=waiting.get(msg.id);waiting.delete(msg.id);msg.error?item.reject(msg.error):item.resolve(msg.result);}else if(msg.method==='Runtime.exceptionThrown')errors.push(msg.params.exceptionDetails);else if(msg.method==='Network.requestWillBeSent')requests.push({url:msg.params.request.url,method:msg.params.request.method});});
const send=(method,params={})=>new Promise((resolve,reject)=>{const next=++id;waiting.set(next,{resolve,reject});ws.send(JSON.stringify({id:next,method,params}));});
const evaluate=async expression=>{const response=await send('Runtime.evaluate',{expression,awaitPromise:true,returnByValue:true});if(response.exceptionDetails)throw Error(JSON.stringify(response.exceptionDetails));return response.result.value;};
const check=(value,message)=>{if(!value)throw Error(message);};
const until=async(expression)=>{for(let i=0;i<100;i++){if(await evaluate(expression))return;await pause(100);}throw Error(`Timeout: ${expression}`);};
const click=selector=>evaluate(`document.querySelector(${JSON.stringify(selector)}).click()`);
const upload=async names=>{const {root}=await send('DOM.getDocument');const {nodeId}=await send('DOM.querySelector',{nodeId:root.nodeId,selector:'#file-input'});await send('DOM.setFileInputFiles',{nodeId,files:names.map(name=>path.join(fixtures,name))});await until('state.phase==="select"');};
const navigate=async hash=>{await send('Page.navigate',{url:`http://127.0.0.1:4186/#${hash}`});await until('typeof state!=="undefined"&&document.querySelector("main").children.length>0');};
const shot=async name=>{const result=await send('Page.captureScreenshot',{format:'png'});await writeFile(path.join(folder,name),Buffer.from(result.data,'base64'));};
await send('Page.enable');await send('Runtime.enable');await send('Network.enable');
await send('Network.emulateNetworkConditions',{offline:false,latency:0,downloadThroughput:-1,uploadThroughput:-1});
await send('Browser.setDownloadBehavior',{behavior:'allow',downloadPath:downloads,eventsEnabled:true});
await send('Emulation.setDeviceMetricsOverride',{width:1440,height:1000,deviceScaleFactor:1,mobile:false});
await navigate('tool/merge');
check(await evaluate('document.querySelector(".prototype-label").textContent==="本地处理"'),'Merge marked real');
await shot('merge-live-empty.png');
await click('[data-action="samples"]');await until('state.phase==="select"&&state.files.length===3');
check(await evaluate('state.files.reduce((sum,file)=>sum+file.pages,0)===4'),'Real samples have four pages');
await click('[data-action="run"]');await until('state.phase==="result"');
check(await evaluate('document.querySelector(".result-panel").textContent.includes("4 页")'),'Real example merge');
await click('[data-action="clear"]');
await upload(['A.pdf']);
check(await evaluate('document.querySelector("#run-button").disabled'),'Single input cannot merge');
await upload(['B.pdf','broken.pdf','empty.pdf','form.pdf','encrypted-marker.pdf']);
check(await evaluate('state.files.length===2&&state.files.every(file=>file.pages===2)'),'Only valid PDF files accepted');
for(const label of ['broken.pdf','empty.pdf','form.pdf','encrypted-marker.pdf']){
 check(await evaluate(`document.querySelector('#file-feedback').textContent.includes(${JSON.stringify(label)})`),`Error identifies ${label}`);
}
await click('[data-move="0"][data-direction="1"]');
check(await evaluate('state.files[0].name==="B.pdf"'),'Manual file ordering');
await evaluate('document.querySelector("#merge-order").value="name";document.querySelector("#merge-order").dispatchEvent(new Event("change"))');
check(await evaluate('state.files[0].name==="A.pdf"'),'Filename sort changes actual sequence');
await click('[data-move="0"][data-direction="1"]');
check(await evaluate('document.querySelector("#merge-order").value==="manual"'),'Manual reorder overrides name sort');
await evaluate('document.querySelector("#output-name").value="验收-合并结果.pdf"');
await evaluate('document.querySelector("[data-action=run]").click();document.querySelector("[data-action=cancel]").click()');
await pause(500);
check(await evaluate('state.phase==="select"&&!document.querySelector(".result-panel")&&state.files.length===2'),'Cancel terminates real worker');
await click('[data-action="run"]');await until('state.phase==="result"');
const href=await evaluate('document.querySelector("a[download]").href');
check(await evaluate('document.querySelector("a[download]").download==="验收-合并结果.pdf"'),'Filename avoids duplicate extension');
await shot('merge-live-result.png');
await click('a[download]');
const downloaded=path.join(downloads,'验收-合并结果.pdf');
let bytes;
for(let i=0;i<50;i++){try{bytes=await readFile(downloaded);break;}catch{await pause(100);}}
check(bytes?.subarray(0,5).toString()==='%PDF-','Downloaded file is actual PDF');
await copyFile(downloaded,path.join(fixtures,'browser-merged-B-A.pdf'));
await click('[data-action="cancel"]');
await shot('merge-live-files.png');
await evaluate('document.querySelector("[data-action=run]").click();document.querySelector("a.brand").click()');
await until('!state.tool');await pause(500);
check(await evaluate('document.querySelector("main").classList.contains("page-home")&&state.files.length===0'),'Navigation cancels active work');
await navigate('tool/merge');await upload(['A.pdf','B.pdf']);
await evaluate('document.querySelector("[data-action=clear]").click()');
check(await evaluate('state.files.length===0&&!!document.querySelector(".drop-zone")'),'Clear resets the real input list');
await send('Emulation.setDeviceMetricsOverride',{width:375,height:812,deviceScaleFactor:1,mobile:false});
await upload(['A.pdf','B.pdf']);
check(await evaluate('document.documentElement.scrollWidth<=innerWidth'),'Mobile loaded state does not overflow');
await shot('merge-live-mobile.png');
await send('Network.emulateNetworkConditions',{offline:true,latency:0,downloadThroughput:-1,uploadThroughput:-1});
await send('Page.navigate',{url:'file:///D:/rfx-agent-service/rfx-agent-service/prototypes/office-tools/index.html#tool/merge'});
await until('typeof state!=="undefined"&&!!document.querySelector("#file-input")');
await upload(['B.pdf','A.pdf']);await click('[data-action="run"]');await until('state.phase==="result"');
check(await evaluate('document.querySelector(".result-panel").textContent.includes("4 页")'),'Actual merge works from offline file URL');
const localRequests=requests.filter(request=>/^https?:/.test(request.url));
check(localRequests.every(request=>request.url.startsWith('http://127.0.0.1:4186/')&&request.method==='GET'),'No upload or external HTTP request');
check(errors.length===0,'No unhandled JavaScript exceptions');
await writeFile(path.join(folder,'merge-browser-checks.json'),JSON.stringify({status:'passed',downloadBytes:bytes.length,errors,network:localRequests,checks:['real generated samples','actual local files','minimum file count','invalid encrypted form and empty error messages','filename sorting','manual ordering','real worker cancellation','real PDF download and filename','navigation cancellation','clear','mobile layout','offline file URL merge','no upload or external network']},null,2));
console.log('PASS: real local merge, PDF download, failure messages, worker cancel, navigation, mobile and offline file URL.');
ws.close();
